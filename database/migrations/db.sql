-- 21. FIND DUPLICATE IMAGE URLS
-- ==========================================================

SELECT
    image,
    COUNT(*) AS duplicate_count,
    STRING_AGG(name, ', ' ORDER BY name) AS product_names,
    STRING_AGG(id::text, ', ' ORDER BY id) AS product_ids
FROM public.products
WHERE image IS NOT NULL
  AND TRIM(image) <> ''
GROUP BY image
HAVING COUNT(*) > 1
ORDER BY duplicate_count DESC;


-- Detailed duplicate image report
SELECT
    p.id,
    p.name,
    p.category,
    p.brand,
    p.image,
    d.duplicate_count
FROM public.products p
JOIN (
    SELECT
        image,
        COUNT(*) AS duplicate_count
    FROM public.products
    WHERE image IS NOT NULL
      AND TRIM(image) <> ''
    GROUP BY image
    HAVING COUNT(*) > 1
) d ON p.image = d.image
ORDER BY p.image, p.id;


-- Duplicate URLs used by different product names
SELECT
    image,
    COUNT(DISTINCT name) AS different_products,
    STRING_AGG(
        DISTINCT id::text || ' - ' || name,
        ', '
    ) AS products
FROM public.products
WHERE image IS NOT NULL
  AND TRIM(image) <> ''
GROUP BY image
HAVING COUNT(DISTINCT name) > 1
ORDER BY different_products DESC;


