-- ==========================================================
-- FASHION SHOP WEBSITE - SUPABASE DATABASE
-- PostgreSQL / Supabase
-- ==========================================================

-- 1. USERS TABLE
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(255) UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. PRODUCTS TABLE
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    brand VARCHAR(150),
    description TEXT,
    price NUMERIC(10,2) NOT NULL DEFAULT 0,
    original_price NUMERIC(10,2) DEFAULT 0,
    category VARCHAR(100),
    image TEXT,
    stock INTEGER DEFAULT 0,
    rating NUMERIC(3,2) DEFAULT 0,
    tag VARCHAR(100),
    sizes JSONB DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. CART ITEMS TABLE
CREATE TABLE IF NOT EXISTS public.cart_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
    product_id BIGINT REFERENCES public.products(id) ON DELETE CASCADE,
    size VARCHAR(30),
    quantity INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. WISHLIST ITEMS TABLE
CREATE TABLE IF NOT EXISTS public.wishlist_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
    product_id BIGINT REFERENCES public.products(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(user_id, product_id)
);

-- 5. ORDERS TABLE
CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
    total_amount NUMERIC(10,2) NOT NULL,
    discount NUMERIC(10,2) DEFAULT 0,
    shipping_charge NUMERIC(10,2) DEFAULT 0,
    status VARCHAR(50) DEFAULT 'Placed',
    payment_method VARCHAR(50) DEFAULT 'Cash on Delivery',
    full_name VARCHAR(150),
    phone VARCHAR(20),
    address TEXT,
    city VARCHAR(100),
    state VARCHAR(100),
    pincode VARCHAR(20),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. ORDER ITEMS TABLE
CREATE TABLE IF NOT EXISTS public.order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT REFERENCES public.orders(id) ON DELETE CASCADE,
    product_id BIGINT REFERENCES public.products(id),
    product_name VARCHAR(200),
    price NUMERIC(10,2) NOT NULL,
    size VARCHAR(30),
    quantity INTEGER NOT NULL
);

-- 7. ADDITIONAL / COMPATIBILITY COLUMNS
ALTER TABLE public.products
    ADD COLUMN IF NOT EXISTS brand VARCHAR(150),
    ADD COLUMN IF NOT EXISTS rating NUMERIC(3,2) DEFAULT 0,
    ADD COLUMN IF NOT EXISTS tag VARCHAR(100),
    ADD COLUMN IF NOT EXISTS sizes JSONB DEFAULT '[]'::jsonb;

ALTER TABLE public.cart_items
    ADD COLUMN IF NOT EXISTS size VARCHAR(30);

ALTER TABLE public.orders
    ADD COLUMN IF NOT EXISTS shipping_address TEXT,
    ADD COLUMN IF NOT EXISTS payment_status VARCHAR(30) DEFAULT 'Pending',
    ADD COLUMN IF NOT EXISTS order_status VARCHAR(30) DEFAULT 'Placed';

ALTER TABLE public.order_items
    ADD COLUMN IF NOT EXISTS size VARCHAR(30);


